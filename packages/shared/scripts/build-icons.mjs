// light: the default for larger UI icons (minimal); regular for small ones.
const WEIGHTS = ['light', 'regular', 'fill'];

async function paths(component, weight) {
  const html = await renderToString(createSSRApp({ render: () => h(component, { weight }) }));
  const tags = html.match(/<(?!\/)(?!svg\b|g\b|!--)[a-z]+\b/g) ?? [];
  if (tags.some((t) => t !== '<path')) throw new Error(`non-path element in ${component.name} ${weight}: ${tags}`);
  return [...html.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
}

const entries = [];
for (const [name, componentName] of Object.entries(ICONS)) {
  const component = Phosphor[componentName];
  if (!component) throw new Error(`unknown Phosphor icon ${componentName}`);
  const weights = [];
  for (const weight of WEIGHTS) {
    weights.push(`${weight}: ${JSON.stringify(await paths(component, weight))}`);
  }
  entries.push(`  ${JSON.stringify(name)}: { ${weights.join(', ')} },`);
}

const version = JSON.parse(
  readFileSync(new URL('../../../node_modules/@phosphor-icons/vue/package.json', import.meta.url)),
).version;

const out = `// Generated by scripts/build-icons.mjs from @phosphor-icons/vue ${version} (MIT,
// https://phosphoricons.com). Do not edit by hand: add the icon to the script and rerun it.

export type IconWeight = ${WEIGHTS.map((w) => `'${w}'`).join(' | ')};

export type IconName =
${Object.keys(ICONS).map((n) => `  | '${n}'`).join('\n')};

/** Path data on a 256x256 grid, per weight. */
export const ICONS: Record<IconName, Record<IconWeight, readonly string[]>> = {
${entries.join('\n')}
};
`;

writeFileSync(new URL('../src/icons.ts', import.meta.url), out);
